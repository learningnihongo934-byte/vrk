'use strict';
// The only bridge between VRK's browser UI and the main process. Web pages
// never get this preload; they run fully sandboxed.

const { contextBridge, ipcRenderer } = require('electron');

const send = (channel, ...args) => ipcRenderer.send(`vrk:${channel}`, ...args);
const EVENTS = [
  'focus-address',
  'find-open',
  'find-next',
  'find-result',
  'permission',
  'permission-done',
  'password-offer',
  'toast',
  'burned',
  'settings-section',
  'extensions-changed',
  'theme',
  'suggest-picked',
  'suggestions',
  'suggest-highlight',
  'update-status',
];
// Requests the settings page may make (see browser-ipc.js).
const REQUESTS = new Set([
  'settings:get',
  'settings:set',
  'settings:keep-site',
  'settings:site',
  'settings:forget-sign-ins',
  'settings:restart',
  'settings:update-lists',
  'settings:make-default',
  'os:enter',
  'passwords:remove',
  'passwords:reveal',
  'passwords:check',
  'passwords:set-totp',
  'passwords:totp-code',
  'passwords:scan-qr',
  'update:check',
  'update:restart',
  'backup:export',
  'backup:restore',
  'clipboard:clear',
  'permissions:list',
  'containers:add',
  'containers:update',
  'containers:remove',
  'permissions:revoke',
  'passkeys:remove',
  'extensions:list',
  'extensions:set-enabled',
  'extensions:remove',
  'extensions:set-access',
  'extensions:options',
  'extensions:install-file',
  'extensions:install-store',
  'import:detect',
  'import:browser',
  'import:file',
  'import:choose-folder',
  'import:privacy-settings',
  'settings:set-mode',
  'suggest',
  'history:list',
  'history:remove',
  'history:clear',
  'history:top',
  'themes:list',
  'themes:save',
  'themes:delete',
  'themes:apply',
  'themes:choose-media',
  'themes:export',
  'themes:import',
]);
// Extension toolbar buttons talk to electron-chrome-extensions in VRK's main profile.
const crx = (name, ...args) => ipcRenderer.invoke('crx-msg-remote', 'vrk-main', name, ...args);

contextBridge.exposeInMainWorld('vrk', {
  ready: () => send('ui-ready'),
  newTab: (tor = false) => send('new-tab', Boolean(tor)),
  newContainerTab: (id) => send('new-container-tab', String(id)),
  closeTab: (id) => send('close-tab', Number(id)),
  activateTab: (id) => send('activate-tab', Number(id)),
  toggleMute: (id) => send('toggle-mute', Number(id)),
  navigate: (text) => send('navigate', String(text)),
  back: () => send('back'),
  forward: () => send('forward'),
  reload: () => send('reload'),
  stop: () => send('stop'),
  burn: () => send('burn'),
  retry: () => send('retry'),
  loadInsecure: () => send('load-insecure'),
  dangerBack: () => send('danger-back'),
  dangerVisit: () => send('danger-visit'),
  vpnOff: () => send('vpn-off'),
  vpnRetry: () => send('vpn-retry'),
  torRetry: () => send('tor-retry'),
  torIdentity: () => send('tor-identity'),
  toggleBookmark: () => send('toggle-bookmark'),
  openBookmark: (id, how) => send('open-bookmark', String(id), String(how)),
  bookmarkFolder: (id, x, y) => send('bookmark-folder', String(id), Number(x), Number(y)),
  bookmarkContext: (id, x, y) => send('bookmark-context', String(id), Number(x), Number(y)),
  openSettings: (section) => send('open-settings', section ? String(section) : ''),
  menu: (name, x, y) => send('menu', String(name), Number(x), Number(y)),
  find: (text, forward, isNew) => send('find', String(text), Boolean(forward), Boolean(isNew)),
  stopFind: () => send('stop-find'),
  setChromeHeight: (height) => send('chrome-height', Number(height)),
  answerPermission: (id, allow) => send('permission', Number(id), Boolean(allow)),
  answerPassword: (id, action, keep) => send('password-answer', Number(id), String(action), Boolean(keep)),
  revealDownload: (id) => send('reveal-download', Number(id)),
  storeInstall: (store, id) => send('store-install', String(store), String(id)),
  splashDone: () => send('splash-done'),
  unlock: () => send('unlock'),
  suggestHighlight: (index) => send('suggest-highlight', Number(index)),
  suggestHide: () => send('suggest-hide'),
  suggestPick: (index) => send('suggest-pick', Number(index)),
  reopenClosed: () => send('reopen-closed'),
  openInternal: (page) => send('open-internal', String(page)),
  openUrl: (url, how = 'current') => send('open-url', String(url), String(how)),
  request: (name, ...args) => {
    if (!REQUESTS.has(name)) return Promise.reject(new Error(`Unknown request ${name}`));
    return ipcRenderer.invoke(`vrk:${name}`, ...args);
  },
  extensionActions: {
    getState: () => crx('browserAction.getState'),
    activate: (details) => crx('browserAction.activate', details),
    observe: (callback) => {
      crx('browserAction.addObserver');
      ipcRenderer.on('browserAction.update', () => callback());
    },
  },
  onState: (callback) => ipcRenderer.on('vrk:state', (_event, state) => callback(state)),
  onEvent: (callback) => {
    for (const name of EVENTS) ipcRenderer.on(`vrk:${name}`, (_event, payload) => callback(name, payload));
  },
});
